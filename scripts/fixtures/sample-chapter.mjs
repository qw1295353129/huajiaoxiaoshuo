/** 拼成一段够长的样本（约 700+ 字） */
export function sampleChapter() {
  return SENTENCES.join('');
}

/** 给测试用的另一种样本，句子不同但同样够长 */
export function sampleChapterB() {
  return SENTENCES.slice()
    .reverse()
    .map((s) => s.replace('沈砚', '周砚').replace('林晚', '苏晚'))
    .join('');
}

const n = sampleChapter().length;
if (n < 600) {
  throw new Error('样本太短：' + n + ' 字。拆书测试需要 600 字以上。');
}
