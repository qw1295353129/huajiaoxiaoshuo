/**
 * 更新日志。
 *
 * 约定：只记录用户能感知的变化，不写"重构了 xx 模块"这类内部改动。
 * 每个版本分三类，顺序固定为 新增 → 优化 → 修复。
 */

export type ChangeKind = "added" | "improved" | "fixed";

export interface ChangeEntry {
  kind: ChangeKind;
  /** 每条一句话，说清"改了什么、对你有什么用" */
  items: string[];
}

export interface Release {
  version: string;
  date: string;
  /** 一句话概括这个版本的主题 */
  headline?: string;
  changes: ChangeEntry[];
}

